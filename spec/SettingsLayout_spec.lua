local mock = require("spec.wow_mock")

describe("opt-in settings layout", function()
    local ns, LC, parent

    local function CreateRow(container)
        local row = CreateFrame("Frame", nil, container)
        row:SetHeight(24)
        function row:SetCompactLayout(width)
            self._compactWidth = width
            self:SetHeight(48)
        end
        return row
    end

    before_each(function()
        ns = mock.Reload()
        assert(loadfile("DragonWidgets/LayoutConstants.lua"))()
        LC = ns.LayoutConstants
        parent = CreateFrame("Frame")
        parent:SetWidth(900)
    end)

    it("leaves legacy anchors and heights unchanged without opt-in", function()
        local row = CreateRow(parent)
        local bottom = LC.AnchorWidget(row, parent, -30, 16, -20)
        assert.are.equal(-54, bottom)
        assert.are.equal(24, row:GetHeight())
        assert.is_nil(parent._settingsLayout)
        assert.are.equal(16, row._points[1].x)
        assert.are.equal(-20, row._points[2].x)
    end)

    it("pairs adjacent controls in declaration order and flushes the final row", function()
        LC.BeginSettingsLayout(parent)
        local first, second, third = CreateRow(parent), CreateRow(parent), CreateRow(parent)
        LC.AnchorWidget(first, parent, -10)
        LC.AnchorWidget(second, parent, -40)
        LC.AnchorWidget(third, parent, -70)
        local height = LC.EndSettingsLayout(parent)

        assert.are.equal(428, first:GetWidth())
        assert.are.equal(10, first._points[1].x)
        assert.are.equal(462, second._points[1].x)
        assert.are.equal(first._points[1].y, second._points[1].y)
        assert.are.equal(-58, third._points[1].y)
        assert.are.equal(126, height)
    end)

    it("stacks controls at narrow widths and reflows on resize", function()
        LC.BeginSettingsLayout(parent)
        local first, second = CreateRow(parent), CreateRow(parent)
        LC.AnchorWidget(first, parent, -10)
        LC.AnchorWidget(second, parent, -40)
        LC.EndSettingsLayout(parent)

        parent:SetWidth(620)
        assert.are.equal(600, first:GetWidth())
        assert.are.equal(10, second._points[1].x)
        assert.are.equal(-58, second._points[1].y)
        assert.are.equal(126, parent:GetHeight())

        parent:SetWidth(900)
        assert.are.equal(first._points[1].y, second._points[1].y)
        assert.are.equal(78, parent:GetHeight())
    end)

    it("does not register a control twice when it is anchored again", function()
        LC.BeginSettingsLayout(parent)
        local row = CreateRow(parent)
        LC.AnchorWidget(row, parent, -10)
        LC.AnchorWidget(row, parent, -60)
        LC.EndSettingsLayout(parent)
        assert.are.equal(1, #parent._settingsLayout.widgets)
        assert.are.equal(1, #row._points)
        assert.are.equal(78, parent:GetHeight())
    end)

    it("preserves full-width heading and description boundaries", function()
        mock.LoadWidget("Header.lua")
        mock.LoadWidget("Description.lua")
        LC.BeginSettingsLayout(parent)
        local first = CreateRow(parent)
        local heading = ns.Widgets.CreateHeader(parent, "Appearance")
        local description = ns.Widgets.CreateDescription(parent, "Configure the preview.")
        local last = CreateRow(parent)
        LC.AnchorWidget(first, parent, -10)
        LC.AnchorWidget(heading, parent, -40)
        LC.AnchorWidget(description, parent, -70)
        LC.AnchorWidget(last, parent, -100)
        LC.EndSettingsLayout(parent)

        assert.are.equal(880, heading:GetWidth())
        assert.are.equal(880, description:GetWidth())
        assert.are.equal(-58, heading._points[1].y)
        assert.is_true(last._points[1].y < description._points[1].y)
        assert.are.equal(10, last._points[1].x)
    end)

    it("recursively sizes sections when their paired rows become stacked", function()
        mock.LoadWidget("Section.lua")
        parent:SetWidth(1000)
        LC.BeginSettingsLayout(parent)
        local section = ns.Widgets.CreateSection(parent, "General")
        local first, second = CreateRow(section.content), CreateRow(section.content)
        LC.AnchorWidget(first, section.content, -10)
        LC.AnchorWidget(second, section.content, -40)
        LC.AnchorSection(section, parent, -10)
        LC.EndSettingsLayout(parent)

        assert.are.equal(48, section.content:GetHeight())
        assert.are.equal(96, section:GetHeight())
        assert.are.equal(126, parent:GetHeight())
        parent:SetWidth(620)
        assert.are.equal(96, section.content:GetHeight())
        assert.are.equal(144, section:GetHeight())
        assert.are.equal(174, parent:GetHeight())
    end)

    it("gives explicit full-width controls and noncompact content their own rows", function()
        LC.BeginSettingsLayout(parent)
        local first, full, last = CreateRow(parent), CreateRow(parent), CreateRow(parent)
        full._layoutFullWidth = true
        local grid = CreateFrame("Frame", nil, parent)
        grid:SetHeight(100)
        LC.AnchorWidget(first, parent, -10)
        LC.AnchorWidget(full, parent, -40)
        LC.AnchorWidget(grid, parent, -70)
        LC.AnchorWidget(last, parent, -170)
        LC.EndSettingsLayout(parent)
        assert.are.equal(880, full:GetWidth())
        assert.are.equal(880, grid:GetWidth())
        assert.are.equal(-58, full._points[1].y)
        assert.are.equal(-106, grid._points[1].y)
        assert.are.equal(-206, last._points[1].y)

        grid:SetHeight(140)
        assert.are.equal(-246, last._points[1].y)
        assert.are.equal(314, parent:GetHeight())
    end)

    it("retains the same collected entries and separators over repeated reflows", function()
        mock.LoadWidget("Toggle.lua")
        LC.BeginSettingsLayout(parent)
        local row = ns.Widgets.CreateToggle(parent, { label = "Enabled" })
        LC.AnchorWidget(row, parent, -10)
        LC.EndSettingsLayout(parent)
        local entries, separator = parent._settingsLayout.widgets, row._rowSeparator
        for _ = 1, 5 do LC.EndSettingsLayout(parent) end
        assert.are.equal(entries, parent._settingsLayout.widgets)
        assert.are.equal(separator, row._rowSeparator)
        assert.are.equal(1, #entries)
        assert.are.equal(1, #row._points)
        assert.is_false(parent._settingsLayout.layingOut)
    end)

    it("places compact dropdown, input, slider, toggle and swatch controls on the right", function()
        mock.LoadWidget("ScrollFrame.lua")
        mock.LoadWidget("Dropdown.lua")
        mock.LoadWidget("TextInput.lua")
        mock.LoadWidget("Slider.lua")
        mock.LoadWidget("Toggle.lua")
        mock.LoadWidget("ColorPicker.lua")
        mock.LoadWidget("Button.lua")
        local dropdown = ns.Widgets.CreateDropdown(parent, { label = "Font", values = {} })
        local input = ns.Widgets.CreateTextInput(parent, { label = "Name" })
        local slider = ns.Widgets.CreateSlider(parent, { label = "Scale" })
        local toggle = ns.Widgets.CreateToggle(parent, { label = "Enabled" })
        local color = ns.Widgets.CreateColorPicker(parent, { label = "Tint" })
        local button = ns.Widgets.CreateButton(parent, { text = "Reset" })
        assert.are.equal(42, dropdown:GetHeight())
        assert.are.equal(40, input:GetHeight())
        assert.are.equal(55, slider:GetHeight())
        assert.are.equal(24, button:GetHeight())

        for _, widget in ipairs({ dropdown, input, slider, toggle, color, button }) do
            widget:SetCompactLayout(320)
        end
        assert.are.equal("RIGHT", dropdown._button._points[1].point)
        assert.are.equal("RIGHT", input._editBox._points[1].point)
        assert.are.equal("RIGHT", slider._editBox._points[1].point)
        assert.are.equal("RIGHT", toggle._box._points[1].point)
        assert.are.equal("RIGHT", color._border._points[1].point)
        assert.are.equal(48, slider:GetHeight())
        assert.are.equal(153, dropdown._button:GetWidth())
        assert.are.equal(95, slider._slider:GetWidth())
        assert.are.equal(120, button:GetWidth())
        assert.are.equal(28, button:GetHeight())
    end)

    it("refreshes nested values without invoking setters or firing change events", function()
        mock.LoadWidget("Section.lua")
        mock.LoadWidget("Toggle.lua")
        mock.LoadWidget("Slider.lua")
        mock.LoadWidget("TextInput.lua")
        local enabled, value, text = false, 20, "Before"
        local writes, events = 0, 0
        local function Set() writes = writes + 1 end
        ns.On("OnWidgetChanged", function() events = events + 1 end)
        ns.On("OnAppearanceChanged", function() events = events + 1 end)

        LC.BeginSettingsLayout(parent)
        local section = ns.Widgets.CreateSection(parent, "Settings")
        local toggle = ns.Widgets.CreateToggle(section.content, { get = function() return enabled end, set = Set })
        local slider = ns.Widgets.CreateSlider(section.content, { get = function() return value end, set = Set })
        local input = ns.Widgets.CreateTextInput(parent, { get = function() return text end, set = Set })
        LC.AnchorWidget(toggle, section.content, -10)
        LC.AnchorWidget(slider, section.content, -40)
        LC.AnchorSection(section, parent, -10)
        LC.AnchorWidget(input, parent, -100)
        LC.EndSettingsLayout(parent)
        enabled, value, text = true, 75, "After"
        LC.RefreshSettingsLayout(parent)

        assert.is_true(toggle:GetValue())
        assert.are.equal(75, slider:GetValue())
        assert.are.equal("After", input:GetValue())
        assert.are.equal(0, writes)
        assert.are.equal(0, events)
    end)
end)
